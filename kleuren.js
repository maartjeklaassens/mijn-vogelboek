export function kleurenVoor(s){return catalog.get(String(s.scientific||'').trim().toLowerCase()) || [];}
export function heeftKleur(s, kleur){return kleurenVoor(s).includes(kleur);}
export function ingedeeldAantal(soorten){return soorten.filter(s=>kleurenVoor(s).length).length;}
